"""Convert Ableton Live sampler presets to SFZ for Synthient's sampler, and Live MIDI clips to .mid.

Usage:
    python ableton_to_sfz.py SOURCE OUT_DIR [--map sample_map.json] [--midi-out DIR] [--force]

SOURCE is an .adv/.adg/.alc file, a folder, or a .zip of Ableton's Resources folders.

What converts:
* Simpler and Sampler presets (.adv): key/velocity zones, root key, tuning, gain, pan,
  sample start/end, loops, amp envelope, low-pass filter, pitch-bend range.
* Drum Racks (.adg): one key per pad (Ableton's receiving note), choke groups, pad gain/pan.
* Instrument Racks (.adg) whose chains hold Simpler/Sampler (or nested racks of them):
  chain key/velocity zones and chain gain/pan.
* MIDI clips (.alc): notes (enabled ones), at the clip's tempo, written as .mid.

What does not: Ableton's synths (Operator, Wavetable, Analog, Drift, Tension, Collision,
Electric), Max for Live devices, audio/MIDI effects, modulation (LFOs, aux envelopes, macros),
Simpler slicing mode, warping. Racks that mix samplers with those keep only the sampler parts.

Sample files are looked up in this order: the --map JSON (Ableton pack path -> file, written
when the Core Library samples were imported), then the preset's own paths next to SOURCE,
then by file name in the map's folder.

An existing output is only overwritten if this script wrote it (first-line marker) or --force.
Last stdout line is a JSON summary.
"""
import gzip
import json
import math
import os
import re
import struct
import sys
import zipfile
import xml.etree.ElementTree as ET
from collections import Counter

MARKER = "// Generated by ableton_to_sfz.py"
SAMPLERS = ("OriginalSimpler", "MultiSampler")
RACKS = ("InstrumentGroupDevice", "DrumGroupDevice")
SYNTHS = ("Operator", "InstrumentVector", "UltraAnalog", "Drift", "StringStudio", "Collision",
          "LoungeLizard", "InstrumentImpulse", "InstrumentMeld", "MxDeviceInstrument", "PluginDevice")
SKIP_DIRS = re.compile(r"/(Defaults|Misc|Lessons|Templates)/", re.I)


# ---------------------------------------------------------------- XML helpers

def val(el, path, default=None, cast=float):
    """Value of a parameter: <X Value=".."/> or an automatable <X><Manual Value=".."/></X>."""
    e = el.find(path) if path else el
    if e is None:
        return default
    m = e.find("Manual")
    v = m.get("Value") if m is not None else e.get("Value")
    if v is None:
        return default
    if cast is bool:
        return v.lower() == "true"
    try:
        return cast(v)
    except ValueError:
        return default


def rng(el, path, lo=0, hi=127):
    e = el.find(path)
    if e is None:
        return lo, hi
    return int(val(e, "Min", lo)), int(val(e, "Max", hi))


def device_of(preset):
    """The device element inside an AbletonDevicePreset/GroupDevicePreset (or the element itself)."""
    if preset.tag in ("AbletonDevicePreset", "GroupDevicePreset"):
        d = preset.find("Device")
        return next(iter(d), None) if d is not None else None
    return preset


def read_xml(data):
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    return ET.fromstring(data)


# ---------------------------------------------------------------- sample lookup

class Samples:
    def __init__(self, map_path, source_root):
        self.map, self.base, self.by_name = {}, None, {}
        self.source_root = source_root
        if map_path:
            with open(map_path, encoding="utf-8") as f:
                self.map = {k.lower(): v for k, v in json.load(f)["samples"].items()}
            self.base = os.path.dirname(os.path.abspath(map_path))
            for rel in self.map.values():
                self.by_name.setdefault(os.path.basename(rel).lower(), rel)

    def find(self, sample_ref):
        """Absolute path of the sample, or None."""
        fr = sample_ref.find("FileRef")
        if fr is None:
            return None
        rel = (fr.find("RelativePath").get("Value") if fr.find("RelativePath") is not None else "") or ""
        absp = (fr.find("Path").get("Value") if fr.find("Path") is not None else "") or ""
        if not rel and fr.find("RelativePath") is not None:  # Live 9/10 style: <RelativePathElement Dir=..>
            dirs = [e.get("Dir", "") for e in fr.find("RelativePath")]
            name = fr.find("Name").get("Value") if fr.find("Name") is not None else ""
            rel = "/".join(dirs + [name])
        rel = rel.replace("\\", "/").lstrip("./")
        if self.map:
            hit = self.map.get(rel.lower())
            if hit:
                return os.path.join(self.base, hit)
            m = re.search(r"Core Library/(.+)$", absp.replace("\\", "/"), re.I)
            if m and m.group(1).lower() in self.map:
                return os.path.join(self.base, self.map[m.group(1).lower()])
        if self.source_root and rel:
            p = os.path.normpath(os.path.join(self.source_root, rel))
            if os.path.isfile(p):
                return p
        if absp and os.path.isfile(absp):
            return absp
        name = os.path.basename(rel or absp).lower()
        if name in self.by_name:
            return os.path.join(self.base, self.by_name[name])
        return None


# ---------------------------------------------------------------- preset -> regions

class Ctx:
    """What an enclosing rack chain does to the notes and sound reaching a device."""
    def __init__(self, klo=0, khi=127, vlo=1, vhi=127, gain_db=0.0, pan=0.0, pad=None, send=None, choke=0):
        self.klo, self.khi, self.vlo, self.vhi = klo, khi, vlo, vhi
        self.gain_db, self.pan, self.pad, self.send, self.choke = gain_db, pan, pad, send, choke

    def child(self, **kw):
        c = Ctx(self.klo, self.khi, self.vlo, self.vhi, self.gain_db, self.pan, self.pad, self.send, self.choke)
        for k, v in kw.items():
            setattr(c, k, v)
        return c


def lin_db(x):
    return 20.0 * math.log10(x) if x and x > 0 else -144.0


def sampler_regions(dev, ctx, samples, warn):
    if not val(dev, "On", True, bool):
        return []
    simpler = dev.tag == "OriginalSimpler"
    mode = int(val(dev, "Globals/PlaybackMode", 0))
    if simpler and mode == 2:
        warn["Simpler slicing mode (skipped)"] += 1
        return []
    one_shot = simpler and mode == 1
    player = dev.find("Player")
    transpose = val(dev, "Pitch/TransposeKey", 0.0) + val(dev, "Pitch/TransposeFine", 0.0) / 100.0
    shift = int(val(dev, "Globals/KeyZoneShift", 0))
    selector = val(player, "SampleSelector", 0.0)
    vp = dev.find("VolumeAndPan")
    dev_db = val(vp, "Volume", 0.0)
    dev_pan = val(vp, "Panorama", 0.0)
    veltrack = max(0.0, min(100.0, val(vp, "VolumeVelScale", 1.0) * 100.0))
    env = vp.find("Envelope")
    bend = val(dev, "Globals/PitchBendRange", 2.0)
    lm = player.find("LoopModulators")
    m_start, m_len = val(lm, "SampleStart", 0.0), val(lm, "SampleLength", 1.0)
    m_loop_on, m_loop_len = val(lm, "LoopOn", False, bool), val(lm, "LoopLength", 1.0)

    filt = None
    f = dev.find("Filter")
    if f is not None and val(f, "IsOn", False, bool):
        sf = f.find(".//SimplerFilter")
        if sf is not None:
            ftype, x = int(val(sf, "Type", 0)), val(sf, "X", 0.0)
            if ftype == 0 or (ftype == 4 and x < 0.1):
                freq = val(sf, "Freq", 20000.0)
                fenv = sf.find("Envelope")
                env_on = fenv is not None and val(fenv, "IsOn", False, bool) and abs(val(fenv, "Amount", 0.0)) > 0.01
                # Synthient's sampler has a fixed cutoff only. A cutoff that Ableton opens with the
                # filter envelope, velocity or key would sound muffled if kept, so drop it instead.
                if env_on or val(sf, "ModByVelocity", 0.0) > 0.2 or val(sf, "ModByPitch", 0.0) > 0.2:
                    warn["envelope/velocity/key-driven filter (dropped)"] += 1
                elif freq < 19000.0:
                    filt = (freq, val(sf, "Res", 0.0))
            else:
                warn["non-low-pass filter (dropped)"] += 1
    if any(dev.find(p) is not None and val(dev.find(p), "IsOn", False, bool) for p in ("Lfo", "AuxEnv")):
        warn["LFO / aux envelope (dropped)"] += 1

    out = []
    for part in player.iter("MultiSamplePart"):
        if not val(part, "IsActive", True, bool):
            continue
        slo, shi = rng(part, "SelectorRange", 0, 127)
        if not slo <= selector <= shi:
            continue
        ref = part.find("SampleRef")
        path = samples.find(ref) if ref is not None else None
        if not path:
            warn["sample not found"] += 1
            continue
        klo, khi = rng(part, "KeyRange")
        vlo, vhi = rng(part, "VelocityRange", 1, 127)
        vlo, vhi = max(vlo, ctx.vlo, 1), min(vhi, ctx.vhi)
        if vlo > vhi:
            continue
        root = int(val(part, "RootKey", 60))
        keytrack = val(part, "TuneScale", 100.0)
        cents = val(part, "Detune", 0.0) + transpose * 100.0

        if ctx.pad is not None:  # drum pad: the chain always receives ctx.send
            n = ctx.send + shift
            if not (klo <= n <= khi and ctx.klo <= ctx.send <= ctx.khi):
                continue
            lo = hi = center = ctx.pad
            cents += (ctx.send - root) * keytrack
        else:
            lo, hi = max(klo - shift, ctx.klo, 0), min(khi - shift, ctx.khi, 127)
            if lo > hi:
                continue
            center = root

        s0, e0 = int(val(part, "SampleStart", 0)), int(val(part, "SampleEnd", 0))
        length = max(0, e0 - s0)
        start = s0 + int(m_start * length)
        end = min(e0, start + int(m_len * length)) if length else 0
        r = {
            "lokey": lo, "hikey": hi, "pitch_keycenter": center,
            "lovel": vlo, "hivel": vhi,
            "volume": round(dev_db + lin_db(val(part, "Volume", 1.0)) + ctx.gain_db, 2),
            "pan": round(max(-100.0, min(100.0, (val(part, "Panorama", 0.0) + dev_pan + ctx.pan) * 100.0)), 1),
            "amp_veltrack": round(veltrack, 1),
            "bend_up": int(bend * 100), "bend_down": -int(bend * 100),
        }
        if abs(cents) > 0.05:
            r["tune"] = round(cents, 1)
        if keytrack != 100 and ctx.pad is None:
            r["pitch_keytrack"] = round(keytrack, 1)
        if start > 0:
            r["offset"] = start
        if end > start:
            r["end"] = end

        if one_shot:
            r["loop_mode"] = "one_shot"
            fade_in = val(vp, "OneShotEnvelope/FadeInTime", 0.0)
            if fade_in > 0:
                r["ampeg_attack"] = round(fade_in / 1000.0, 4)
        else:
            loop = None
            if simpler:
                if m_loop_on and end > start:
                    loop = (end - int(m_loop_len * (end - start)), end)
            else:
                sl = part.find("SustainLoop")
                if sl is not None and int(val(sl, "Mode", 0)) in (1, 2):
                    a, b = int(val(sl, "Start", 0)), int(val(sl, "End", 0))
                    if b > a + 8:
                        loop = (a, b)
                        if int(val(sl, "Mode", 0)) == 2:
                            warn["back-and-forth loop (played forward)"] += 1
            if loop:
                r["loop_mode"], r["loop_start"], r["loop_end"] = "loop_continuous", loop[0], loop[1]
                if "end" in r and r["end"] < loop[1]:
                    r["end"] = loop[1]
            else:
                r["loop_mode"] = "no_loop"
            if env is not None:
                r["ampeg_attack"] = round(val(env, "AttackTime", 0.1) / 1000.0, 4)
                r["ampeg_decay"] = round(val(env, "DecayTime", 600.0) / 1000.0, 4)
                r["ampeg_sustain"] = round(max(0.0, min(1.0, val(env, "SustainLevel", 1.0))) * 100.0, 2)
                r["ampeg_release"] = round(max(0.001, val(env, "ReleaseTime", 50.0) / 1000.0), 4)
        if filt:
            r["cutoff"] = round(max(20.0, min(20000.0, filt[0])), 1)
            r["resonance"] = round(max(0.0, min(24.0, filt[1] * 16.0)), 1)
        if ctx.choke:
            r["group"] = r["off_by"] = 100 + ctx.choke
        r["sample"] = path
        out.append(r)
    return out


def branch_mix(branch):
    mixer = branch.find("MixerPreset")
    d = device_of(mixer.find("AbletonDevicePreset")) if mixer is not None and mixer.find("AbletonDevicePreset") is not None else None
    if d is None:
        d = branch.find("MixerDevice")  # inside a full device tree
    if d is None:
        return True, 0.0, 0.0
    return val(d, "Speaker", True, bool), lin_db(val(d, "Volume", 1.0)), val(d, "Panorama", 0.0)


def chain_presets(branch):
    """The devices in a rack chain (preset form or device-tree form)."""
    dp = branch.find("DevicePresets")
    if dp is not None:
        return list(dp)
    dc = branch.find("DeviceChain/DeviceChain/Devices")
    return list(dc) if dc is not None else []


def walk(preset, ctx, samples, warn, kinds):
    """Regions produced by a device preset (and anything nested in it)."""
    dev = device_of(preset)
    if dev is None:
        return []
    if dev.tag in SAMPLERS:
        kinds.add(dev.tag)
        return sampler_regions(dev, ctx, samples, warn)
    if dev.tag in SYNTHS:
        warn[f"{dev.tag} (Ableton synth, dropped)"] += 1
        return []
    if dev.tag not in RACKS:
        return []  # audio/MIDI effects: ignored
    if not val(dev, "On", True, bool):
        return []
    kinds.add(dev.tag)
    chain_sel = val(dev, "ChainSelector", 0.0)
    branches = preset.find("BranchPresets") if preset.tag == "GroupDevicePreset" else dev.find("Branches")
    out = []
    for br in list(branches) if branches is not None else []:
        slo, shi = rng(br, "BranchSelectorRange", 0, 127)
        if not slo <= chain_sel <= shi:
            continue
        on, g, p = branch_mix(br)
        if not on:
            continue
        sub = ctx.child(gain_db=ctx.gain_db + g, pan=ctx.pan + p)
        zs = br.find("ZoneSettings") if br.find("ZoneSettings") is not None else br.find("BranchInfo")
        if dev.tag == "DrumGroupDevice":
            if ctx.pad is not None:
                warn["drum rack inside a drum pad (skipped)"] += 1
                continue
            recv = int(val(zs, "ReceivingNote", 0))
            pad = 128 - recv
            if not (0 <= pad <= 127 and ctx.klo <= pad <= ctx.khi):
                continue
            # the pad's chain always receives SendingNote; outer key zones were applied to the pad above
            sub.pad, sub.send = pad, int(val(zs, "SendingNote", 60))
            sub.klo, sub.khi = 0, 127
            sub.choke = int(val(zs, "ChokeGroup", 0))
        elif zs is not None:
            klo, khi = rng(zs, "KeyRange")
            vlo, vhi = rng(zs, "VelocityRange", 1, 127)
            sub.klo, sub.khi = max(ctx.klo, klo), min(ctx.khi, khi)
            sub.vlo, sub.vhi = max(ctx.vlo, vlo), min(ctx.vhi, vhi)
            if sub.vlo > sub.vhi or (ctx.pad is None and sub.klo > sub.khi):
                continue
        for p_ in chain_presets(br):
            out += walk(p_, sub, samples, warn, kinds)
    return out


# ---------------------------------------------------------------- SFZ writing

OPCODE_ORDER = ["lokey", "hikey", "pitch_keycenter", "pitch_keytrack", "lovel", "hivel", "tune", "volume",
                "pan", "amp_veltrack", "offset", "end", "loop_mode", "loop_start", "loop_end",
                "ampeg_attack", "ampeg_decay", "ampeg_sustain", "ampeg_release", "cutoff", "resonance",
                "group", "off_by", "bend_up", "bend_down"]


LOUDEST_ZONE_DB = -6.0  # Ableton presets carry 6-20 dB of headroom; match Synthient's other instruments


def write_sfz(path, regions, title, source, sample_root):
    lift = LOUDEST_ZONE_DB - max(r["volume"] for r in regions)
    lines = [MARKER, f"// {title}", f"// from {source}"]
    if lift > 0.05:
        for r in regions:
            r["volume"] = round(r["volume"] + lift, 2)
        lines.append(f"// gain raised {lift:.1f} dB so the loudest zone sits at {LOUDEST_ZONE_DB:.0f} dB")
    lines += ["", "<control>"]
    root = sample_root.replace("\\", "/").rstrip("/") + "/"
    lines.append(f"default_path={root}")
    lines.append("")
    for r in regions:
        s = r["sample"].replace("\\", "/")
        sample = s[len(root):] if s.lower().startswith(root.lower()) else s
        ops = " ".join(f"{k}={r[k]}" for k in OPCODE_ORDER if k in r)
        lines.append(f"<region> {ops}")
        lines.append(f"sample={sample}")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def may_write(path, force):
    if force or not os.path.exists(path):
        return True
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.readline().startswith(MARKER)


# ---------------------------------------------------------------- MIDI clips

def write_mid(path, notes, bpm, length_beats, name):
    ppq = 480
    ev = []
    for start, dur, key, vel in notes:
        t0 = int(round(start * ppq))
        t1 = max(t0 + 1, int(round((start + dur) * ppq)))
        ev.append((t0, 1, 0x90, key, max(1, min(127, vel))))
        ev.append((t1, 0, 0x80, key, 0))
    ev.sort(key=lambda e: (e[0], e[1]))

    def vlq(n):
        b = [n & 0x7F]
        while n > 0x7F:
            n >>= 7
            b.insert(0, (n & 0x7F) | 0x80)
        return bytes(b)

    trk = bytearray()
    nm = name.encode("utf-8")[:120]
    trk += vlq(0) + b"\xff\x03" + vlq(len(nm)) + nm
    tempo = int(round(60_000_000 / bpm))
    trk += vlq(0) + b"\xff\x51\x03" + tempo.to_bytes(3, "big")
    trk += vlq(0) + b"\xff\x58\x04\x04\x02\x18\x08"
    t = 0
    for tick, _, st, k, v in ev:
        trk += vlq(tick - t) + bytes([st, k, v])
        t = tick
    end = max(t, int(round(length_beats * ppq)))
    trk += vlq(end - t) + b"\xff\x2f\x00"
    data = b"MThd" + struct.pack(">IHHH", 6, 0, 1, ppq) + b"MTrk" + struct.pack(">I", len(trk)) + bytes(trk)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)


def clip_notes(root):
    """[(clip, notes, start, end)] for every MIDI clip; notes are (beat, dur, key, vel) from clip start."""
    out = []
    for clip in root.iter("MidiClip"):
        cs = val(clip, "CurrentStart", 0.0)
        ce = val(clip, "CurrentEnd", 4.0)
        loop = clip.find("Loop")
        ls = val(loop, "LoopStart", 0.0) if loop is not None else 0.0
        le = val(loop, "LoopEnd", ce - cs) if loop is not None else ce - cs
        notes = []
        for kt in clip.iter("KeyTrack"):
            key = int(val(kt, "MidiKey", 60))
            for n in kt.iter("MidiNoteEvent"):
                if n.get("IsEnabled", "true").lower() != "true":
                    continue
                t, d = float(n.get("Time")), float(n.get("Duration"))
                if t < ls or t >= le:
                    continue
                notes.append((t - ls, min(d, le - t), key, int(round(float(n.get("Velocity", 100))))))
        notes.sort()
        out.append((clip, notes, ls, le))
    return out


# ---------------------------------------------------------------- driver

def iter_sources(source):
    """(display path, relative path, bytes) for every Ableton file under SOURCE."""
    exts = (".adv", ".adg", ".alc")
    if os.path.isfile(source) and source.lower().endswith(".zip"):
        with zipfile.ZipFile(source) as z:
            for n in z.namelist():
                if n.lower().endswith(exts):
                    yield n, n, z.read(n)
    elif os.path.isfile(source):
        with open(source, "rb") as f:
            yield source, os.path.basename(source), f.read()
    else:
        for dp, _, files in os.walk(source):
            for fn in sorted(files):
                if fn.lower().endswith(exts):
                    p = os.path.join(dp, fn)
                    with open(p, "rb") as f:
                        yield p, os.path.relpath(p, source).replace("\\", "/"), f.read()


def out_rel(rel):
    """Output sub-path (no extension) for a preset: <kind folder>/<category>/<name>."""
    r = re.sub(r"^.*?Core Library/", "", rel)
    parts = r.split("/")
    name = os.path.splitext(parts[-1])[0]
    cat = parts[-2] if len(parts) >= 2 else ""
    if r.lower().startswith("midi clips/"):
        return "/".join(p for p in parts[1:-1]) + "/" + name
    return f"{cat}/{name}" if cat else name


def main(argv):
    args, opts, i = [], {}, 0
    while i < len(argv):
        a = argv[i]
        if a in ("--map", "--midi-out"):
            opts[a] = argv[i + 1]; i += 2; continue
        if a.startswith("--"):
            opts[a] = True
        else:
            args.append(a)
        i += 1
    if len(args) < 2:
        print(__doc__)
        return 2
    source, out_dir = args[0], os.path.abspath(args[1])
    midi_dir = os.path.abspath(opts.get("--midi-out", os.path.join(out_dir, "MIDI Clips")))
    force = "--force" in opts
    src_root = source if os.path.isdir(source) else os.path.dirname(os.path.abspath(source))
    samples = Samples(opts.get("--map"), src_root)
    sample_root = samples.base or src_root

    done, stats, report = {}, Counter(), []
    # Newest Live version first so its copy of a preset wins over an older duplicate.
    entries = sorted(iter_sources(source), key=lambda e: (0 if "ableton11" in e[1].lower() else 1, e[1]))
    for disp, rel, data in entries:
        if SKIP_DIRS.search("/" + rel):
            continue
        ext = os.path.splitext(rel)[1].lower()
        try:
            root = read_xml(data)
        except Exception as e:
            stats["unreadable"] += 1
            report.append(("unreadable", rel, str(e)[:80]))
            continue

        if ext == ".alc":
            sub = out_rel(rel)
            key = ("mid", sub.lower())
            if key in done:
                stats["duplicate (other Live version)"] += 1; continue
            done[key] = rel
            tempo = [val(t, None, 120.0) for t in root.iter("Tempo")]
            m = re.search(r"(\d{2,3}(?:\.\d+)?)\s*bpm", rel, re.I)
            bpm = float(m.group(1)) if m else (tempo[0] if tempo else 120.0)
            clips = clip_notes(root)
            if not clips or not any(c[1] for c in clips):
                stats["clip without notes"] += 1; continue
            for ci, (clip, notes, ls, le) in enumerate(c for c in clips if c[1]):
                p = os.path.join(midi_dir, sub + (f" {ci + 1}" if ci else "") + ".mid")
                if not force and os.path.exists(p):
                    stats["midi kept (exists)"] += 1; continue
                write_mid(p, notes, bpm, le - ls, os.path.basename(sub))
                stats["midi clips"] += 1
            continue

        warn, kinds = Counter(), set()
        dev = device_of(root.find("GroupDevicePreset")) if root.find("GroupDevicePreset") is not None else next(iter(root), None)
        top = root.find("GroupDevicePreset") if root.find("GroupDevicePreset") is not None else dev
        if dev is None:
            continue
        if dev.tag not in SAMPLERS + RACKS:
            stats["not a sampler preset"] += 1
            continue
        regions = walk(top, Ctx(), samples, warn, kinds)
        drum = "DrumGroupDevice" in kinds
        if not regions:
            stats["no playable sample parts"] += 1
            report.append(("empty", rel, ", ".join(f"{k} x{n}" for k, n in warn.items())))
            continue
        if not drum and any("Ableton synth" in k for k in warn):
            # Only the sample layer of a synth rack: it would not sound like the preset.
            stats["synth rack, sample layer only (skipped)"] += 1
            report.append(("skipped", rel, ", ".join(f"{k} x{n}" for k, n in warn.items())))
            continue
        sub = ("Drum Kits/" if drum else "") + out_rel(rel)
        sig = ("sig", json.dumps(regions, sort_keys=True))
        if sig in done:  # identical mapping already written (same preset in another Live version)
            stats["duplicate (identical to another preset)"] += 1
            report.append(("duplicate", rel, f"same as {done[sig]}"))
            continue
        key = ("sfz", sub.lower())
        pack_path = re.sub(r"^.*?Core Library/", "", rel).lower()
        if ("pack", pack_path) in done:  # same preset file in an older Live version (small edits)
            stats["duplicate (older Live version)"] += 1
            report.append(("duplicate", rel, "older version of a preset already written"))
            continue
        done[("pack", pack_path)] = rel
        if key in done:
            # same name, different content (e.g. a Sampler and a Simpler "Mod Bass"): keep both
            other = done[key]
            kind = re.sub(r"^.*?Core Library/", "", rel).split("/")
            tag = kind[2] if len(kind) > 3 and kind[0] in ("Devices", "Racks") else kind[0]
            base, n = f"{sub} ({tag})", 1
            sub = base
            while ("sfz", sub.lower()) in done:
                n += 1
                sub = f"{base} {n}"
            key = ("sfz", sub.lower())
            report.append(("renamed", rel, f"name clash with {other}, written as {os.path.basename(sub)}"))
        done[key] = rel
        done[sig] = rel
        p = os.path.join(out_dir, sub + ".sfz")
        if not may_write(p, force):
            stats["kept (not generated by this script)"] += 1; continue
        write_sfz(p, regions, os.path.basename(sub), rel, sample_root)
        stats["drum kits" if drum else "instruments"] += 1
        stats["regions"] += len(regions)
        if warn:
            report.append(("partial" if any("dropped" in k for k in warn) else "note", rel,
                           ", ".join(f"{k} x{n}" for k, n in warn.items())))

    for kind, rel, msg in report:
        print(f"{kind:<10} {rel}: {msg}")
    print(json.dumps({"ok": True, "out": out_dir, "midi_out": midi_dir, **stats}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
