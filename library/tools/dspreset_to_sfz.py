"""Convert Decent Sampler presets (.dspreset / .dslibrary) to SFZ for Synthient's sampler.

Usage:
    python dspreset_to_sfz.py <file.dspreset | file.dslibrary | folder> [--force]

* A .dspreset is converted to <same folder>/<same base name>.sfz so relative sample
  paths keep working. Originals are never modified.
* A .dslibrary (a zip) is extracted to a sibling folder named after it (skipped if
  that folder already exists), then every .dspreset inside is converted.
* A folder: every .dspreset below it is converted (.dslibrary files are extracted).
* An existing .sfz is only overwritten if it was generated by this script
  (first line marker) or --force is given.

See docs/DECENT_SAMPLER_NOTES.md for the mapping and its limitations.
"""
import math
import os
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from collections import Counter

MARKER = "// Generated by dspreset_to_sfz.py"

NOTE_RE = re.compile(r"^([a-gA-G])([#b]?)(-?\d+)$")
NOTE_BASE = {"c": 0, "d": 2, "e": 4, "f": 5, "g": 7, "a": 9, "b": 11}

# Attributes that are understood (directly or as inputs to a mapping).
KNOWN_ATTRS = {
    "path", "rootnote", "lonote", "hinote", "lovel", "hivel", "start", "end",
    "tuning", "globaltuning", "grouptuning", "volume", "globalvolume", "groupvolume",
    "pan", "attack", "decay", "sustain", "release", "loopstart", "loopend",
    "loopenabled", "seqmode", "seqposition", "seqlength", "trigger", "tags",
    "silencedbytags", "silencingmode", "enabled", "name", "ampveltrack",
    "pitchkeytrack", "minversion", "note", "lowvel", "highvel",
}
# Known-but-unsupported attributes (counted as warnings, no effect).
IGNORED_ATTRS = {
    "loopcrossfade", "loopcrossfademode", "glidetime", "glidemode", "attackcurve",
    "decaycurve", "releasecurve", "previousnote", "legatointerval", "pitchenvelope",
    "onloccn", "onhiccn", "modvolume", "lovelocity", "hivelocity", "release_decay",
    "releasedecay", "voicecount", "polyphony", "sequencemode",
}
# Child elements of <DecentSampler> we deliberately skip.
SKIPPED_SECTIONS = {"ui", "effects", "modulators", "midi", "tags", "notesequences",
                    "buses", "keyboard"}


def note_num(v, warn):
    v = str(v).strip()
    try:
        return int(round(float(v)))
    except ValueError:
        pass
    m = NOTE_RE.match(v)
    if not m:
        warn[f"unparseable note '{v}'"] += 1
        return None
    warn["note given as a name (assumed C4=60)"] += 1
    n = NOTE_BASE[m.group(1).lower()] + {"#": 1, "b": -1, "": 0}[m.group(2)]
    return n + (int(m.group(3)) + 1) * 12


def fnum(v, default=None):
    try:
        return float(str(v).strip())
    except (TypeError, ValueError):
        return default


def vol_db(v, warn):
    """Decent Sampler volume: '-3dB' / '-3 dB' style, else a linear gain (1.0 = unity)."""
    s = str(v).strip().lower().replace(" ", "")
    if s.endswith("db"):
        x = fnum(s[:-2])
        if x is None:
            warn[f"bad volume '{v}'"] += 1
            return 0.0
        return x
    x = fnum(s)
    if x is None:
        warn[f"bad volume '{v}'"] += 1
        return 0.0
    if x <= 0:
        return -144.0
    return 20.0 * math.log10(x)


def truthy(v):
    return str(v).strip().lower() in ("true", "1", "yes", "on")


def fmt(x):
    if isinstance(x, float):
        s = f"{x:.4f}".rstrip("0").rstrip(".")
        return s if s not in ("-0", "") else "0"
    return str(x)


def lower_attrs(el):
    return {k.lower(): v for k, v in el.attrib.items()}


def decay_to_sf2(decay_s, sustain_lin):
    """DS decay = time to go from peak to sustain level. Our ampeg_decay is SF2-style:
    the time an exponential fall would need to drop 100 dB (it stops at sustain).
    Pick the SF2 time so the fall reaches the sustain level after decay_s seconds;
    the dB distance is clamped to [1, 60] dB (sustain 0 -> 'silent' at -60 dB)."""
    drop = 60.0 if sustain_lin <= 0.001 else -20.0 * math.log10(sustain_lin)
    drop = min(60.0, max(1.0, drop))
    return min(100.0, decay_s * 100.0 / drop)


class Converter:
    def __init__(self, preset_path):
        self.path = preset_path
        self.warn = Counter()
        self.tag_ids = {}

    def tag_id(self, tag):
        if tag not in self.tag_ids:
            self.tag_ids[tag] = len(self.tag_ids) + 1
        return self.tag_ids[tag]

    def check_attrs(self, attrs, where):
        for k in attrs:
            if k in KNOWN_ATTRS:
                continue
            if k in IGNORED_ATTRS or k.startswith(("filter", "fx", "lfo", "env")):
                self.warn[f"ignored {where} attribute '{k}'"] += 1
            else:
                self.warn[f"unknown {where} attribute '{k}'"] += 1

    def convert(self):
        root = ET.parse(self.path).getroot()
        if root.tag.lower() != "decentsampler":
            raise ValueError(f"not a DecentSampler preset (root <{root.tag}>)")
        for child in root:
            t = child.tag.lower()
            if t in SKIPPED_SECTIONS:
                n = sum(1 for _ in child.iter()) - 1
                self.warn[f"skipped <{child.tag}> section ({n} elements)"] += 1
            elif t != "groups":
                self.warn[f"unknown section <{child.tag}>"] += 1

        regions = []
        for groups in root.iter():
            if groups.tag.lower() != "groups":
                continue
            ga = lower_attrs(groups)
            self.check_attrs(ga, "groups")
            for grp in groups:
                gt = grp.tag.lower()
                if gt != "group":
                    if gt in ("effects", "modulators"):
                        self.warn[f"skipped <{grp.tag}> inside <groups>"] += 1
                    else:
                        self.warn[f"unknown element <{grp.tag}> inside <groups>"] += 1
                    continue
                gra = lower_attrs(grp)
                self.check_attrs(gra, "group")
                if "enabled" in gra and not truthy(gra["enabled"]):
                    self.warn["skipped disabled group"] += 1
                    continue
                samples = [s for s in grp if s.tag.lower() == "sample"]
                for other in grp:
                    if other.tag.lower() != "sample":
                        self.warn[f"skipped <{other.tag}> inside <group>"] += 1
                for s in samples:
                    sa = lower_attrs(s)
                    self.check_attrs(sa, "sample")
                    r = self.region(ga, gra, sa, len(samples))
                    if r is not None:
                        regions.append(r)
        return regions

    def region(self, ga, gra, sa, group_size):
        merged = {}
        merged.update(ga); merged.update(gra); merged.update(sa)
        w = self.warn
        path = merged.get("path")
        if not path:
            w["sample without path skipped"] += 1
            return None
        o = {}
        # keys
        root = note_num(merged["rootnote"], w) if "rootnote" in merged else None
        lo = note_num(merged["lonote"], w) if "lonote" in merged else None
        hi = note_num(merged["hinote"], w) if "hinote" in merged else None
        if root is None:
            root = lo if lo is not None else 60
            w["sample without rootNote (used loNote or 60)"] += 1
        o["lokey"] = lo if lo is not None else 0
        o["hikey"] = hi if hi is not None else 127
        o["pitch_keycenter"] = root
        # velocity
        lv = merged.get("lovel", merged.get("lowvel"))
        hv = merged.get("hivel", merged.get("highvel"))
        if lv is not None:
            o["lovel"] = max(1, min(127, int(fnum(lv, 1))))
        if hv is not None:
            o["hivel"] = max(1, min(127, int(fnum(hv, 127))))
        # tuning: global + group + sample, semitones -> cents (summed, see notes)
        cents = 0.0
        for src, key in ((ga, "globaltuning"), (gra, "grouptuning")):
            if key in src:
                cents += 100.0 * fnum(src[key], 0.0)
        if "tuning" in merged:
            cents += 100.0 * fnum(merged["tuning"], 0.0)
        if abs(cents) > 1e-6:
            o["tune"] = round(cents, 2)
        # volume: each level multiplies (sum in dB)
        db = 0.0
        for src, key in ((ga, "globalvolume"), (ga, "volume"), (gra, "groupvolume"),
                         (gra, "volume"), (sa, "volume")):
            if key in src:
                db += vol_db(src[key], w)
        if abs(db) > 1e-6:
            o["volume"] = round(max(-144.0, db), 2)
        if "pan" in merged:
            p = fnum(merged["pan"], 0.0)
            if p:
                o["pan"] = max(-100.0, min(100.0, p))
        if "ampveltrack" in merged:
            o["amp_veltrack"] = round(100.0 * fnum(merged["ampveltrack"], 1.0), 2)
        if "pitchkeytrack" in merged:
            o["pitch_keytrack"] = round(100.0 * fnum(merged["pitchkeytrack"], 1.0), 2)
        # sample window
        if "start" in merged and fnum(merged["start"], 0) > 0:
            o["offset"] = int(fnum(merged["start"]))
        if "end" in merged and fnum(merged["end"], 0) > 0:
            o["end"] = int(fnum(merged["end"]))
        # loops
        if "loopenabled" in merged:
            if truthy(merged["loopenabled"]):
                o["loop_mode"] = "loop_continuous"
                if "loopstart" in merged:
                    o["loop_start"] = int(fnum(merged["loopstart"], 0))
                if "loopend" in merged:
                    o["loop_end"] = int(fnum(merged["loopend"], 0))
            else:
                o["loop_mode"] = "no_loop"
        elif "loopstart" in merged or "loopend" in merged:
            w["loop points without loopEnabled (ignored; DS default is off)"] += 1
        # envelope
        att = fnum(merged.get("attack"))
        dec = fnum(merged.get("decay"))
        sus = fnum(merged.get("sustain"))
        rel = fnum(merged.get("release"))
        if att is not None:
            o["ampeg_attack"] = round(max(0.0, att), 4)
        if sus is not None:
            sus = max(0.0, min(1.0, sus))
            o["ampeg_sustain"] = round(sus * 100.0, 2)
        if dec is not None and (sus is None or sus < 0.999):
            o["ampeg_decay"] = round(decay_to_sf2(max(0.0, dec), 1.0 if sus is None else sus), 4)
        if rel is not None:
            o["ampeg_release"] = round(max(0.0, rel), 4)
        else:
            o["ampeg_release"] = 0.1  # assumed DS default; our engine default (1 ms) clicks
        # trigger
        trig = str(merged.get("trigger", "attack")).strip().lower()
        if trig in ("release", "first", "legato"):
            o["trigger"] = trig
        elif trig not in ("attack", ""):
            w[f"unknown trigger '{trig}' (treated as attack)"] += 1
        # round robin
        mode = str(merged.get("seqmode", "always")).strip().lower()
        if mode != "always":
            length = int(fnum(merged.get("seqlength"), 0) or 0)
            pos = int(fnum(merged.get("seqposition"), 1) or 1)
            if length <= 0:
                length = max(pos, 1)
                w["seqMode without seqLength (guessed from seqPosition)"] += 1
            pos = max(1, min(length, pos))
            if length > 1:
                if mode == "round_robin":
                    o["seq_length"] = length
                    o["seq_position"] = pos
                elif mode in ("random", "true_random"):
                    o["lorand"] = round((pos - 1) / length, 4)
                    o["hirand"] = round(pos / length, 4)
                    if mode == "random":
                        w["seqMode 'random' mapped to true random (repeats possible)"] += 1
                else:
                    w[f"unknown seqMode '{mode}' (ignored)"] += 1
        # tags -> choke groups
        tags = [t.strip() for t in str(merged.get("tags", "")).split(",") if t.strip()]
        sil = [t.strip() for t in str(merged.get("silencedbytags", "")).split(",") if t.strip()]
        if tags:
            o["group"] = self.tag_id(tags[0])
            if len(tags) > 1:
                w["sample with several tags (only the first becomes its SFZ group)"] += 1
        if sil:
            o["off_by"] = self.tag_id(sil[0])
            if "group" not in o:
                o["group"] = 1000 + o["off_by"]  # needs a group of its own to be choked
            if len(sil) > 1:
                w["silencedByTags with several tags (only the first is used)"] += 1
            mode = str(merged.get("silencingmode", "fast")).strip().lower()
            o["off_mode"] = "normal" if mode == "normal" else "fast"
        o["sample"] = path.replace("\\", "/")
        return o

    def write(self, out_path, regions):
        lines = [MARKER,
                 f"// from: {os.path.basename(self.path)}",
                 "// Do not edit by hand; re-run the converter instead."]
        if self.tag_ids:
            lines.append("// tag -> group: " + ", ".join(f"{t}={i}" for t, i in self.tag_ids.items()))
        lines.append("")
        lines.append("<group>")
        for r in regions:
            parts = [f"{k}={fmt(v)}" for k, v in r.items() if k != "sample"]
            lines.append("<region> " + " ".join(parts) + " sample=" + r["sample"])
        with open(out_path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")


def is_generated(sfz_path):
    try:
        with open(sfz_path, "r", encoding="utf-8", errors="replace") as f:
            return f.readline().startswith(MARKER)
    except OSError:
        return False


def convert_preset(preset_path, force=False, quiet=False):
    """Convert one .dspreset. Returns (sfz_path or None, region_count, warnings Counter)."""
    out = os.path.splitext(preset_path)[0] + ".sfz"
    c = Converter(preset_path)
    try:
        regions = c.convert()
    except (ET.ParseError, ValueError) as e:
        c.warn[f"failed: {e}"] += 1
        if not quiet:
            print(f"FAILED {preset_path}: {e}")
        return None, 0, c.warn
    if os.path.exists(out) and not force and not is_generated(out):
        c.warn["existing hand-made .sfz kept (use --force)"] += 1
        if not quiet:
            print(f"SKIP  {out} exists and was not generated by this script")
        return out, len(regions), c.warn
    if not regions:
        c.warn["no regions"] += 1
    c.write(out, regions)
    if not quiet:
        print(f"OK    {out}  ({len(regions)} regions)")
        for msg, n in sorted(c.warn.items()):
            print(f"      warning x{n}: {msg}")
    return out, len(regions), c.warn


def extract_library(lib_path, quiet=False):
    """Extract a .dslibrary (zip) to a sibling folder; returns the folder."""
    dest = os.path.splitext(lib_path)[0]
    if os.path.isdir(dest):
        if not quiet:
            print(f"EXIST {dest} (already extracted)")
        return dest
    with zipfile.ZipFile(lib_path) as z:
        root = os.path.realpath(dest)
        for info in z.infolist():
            target = os.path.realpath(os.path.join(dest, info.filename))
            if not (target == root or target.startswith(root + os.sep)):
                raise ValueError(f"unsafe path in archive: {info.filename}")
        z.extractall(dest)
    if not quiet:
        print(f"UNZIP {lib_path} -> {dest}")
    return dest


def convert_tree(folder, force=False, quiet=False):
    """Extract every .dslibrary, then convert every .dspreset under folder."""
    results = []
    for dp, _, files in list(os.walk(folder)):
        for fn in files:
            if fn.lower().endswith(".dslibrary"):
                try:
                    extract_library(os.path.join(dp, fn), quiet)
                except (zipfile.BadZipFile, ValueError) as e:
                    print(f"FAILED {os.path.join(dp, fn)}: {e}")
    for dp, _, files in os.walk(folder):
        for fn in sorted(files):
            if fn.lower().endswith(".dspreset"):
                results.append(convert_preset(os.path.join(dp, fn), force, quiet))
    return results


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    force = "--force" in argv
    if not args:
        print(__doc__)
        return 2
    total = Counter()
    for a in args:
        if os.path.isdir(a):
            res = convert_tree(a, force)
        elif a.lower().endswith(".dslibrary"):
            res = convert_tree(extract_library(a), force)
        else:
            res = [convert_preset(a, force)]
        for _, _, w in res:
            total.update(w)
    if total:
        print("\nWarnings (all presets):")
        for msg, n in sorted(total.items()):
            print(f"  x{n}: {msg}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
